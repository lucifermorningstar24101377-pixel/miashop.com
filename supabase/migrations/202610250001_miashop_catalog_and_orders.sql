create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  sku text not null unique,
  category text not null default 'مراقبت پوست',
  brand text not null default 'MiaShop',
  price bigint not null check (price >= 0),
  old_price bigint check (old_price is null or old_price >= price),
  stock integer not null default 0 check (stock >= 0),
  image_url text,
  description text,
  published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.products enable row level security;
revoke all on public.products from anon, authenticated;
grant select on public.products to anon, authenticated;
drop policy if exists "Published products are publicly readable" on public.products;
create policy "Published products are publicly readable" on public.products
  for select to anon, authenticated using (published = true);
create index if not exists products_published_created_at_idx on public.products (published, created_at desc);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text not null unique,
  customer_name text not null,
  phone text not null,
  province text not null,
  city text not null,
  address text not null,
  postal_code text not null,
  payment_method text not null,
  payment_status text not null default 'pending' check (payment_status in ('pending','paid','failed','refunded')),
  order_status text not null default 'awaiting_payment' check (order_status in ('awaiting_payment','paid','processing','shipped','delivered','cancelled','returned')),
  items jsonb not null,
  subtotal bigint not null check (subtotal >= 0),
  shipping_cost bigint not null default 0 check (shipping_cost >= 0),
  total bigint not null check (total >= 0),
  carrier text,
  tracking_code text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.orders enable row level security;
revoke all on public.orders from anon, authenticated;
create index if not exists orders_created_at_idx on public.orders (created_at desc);
